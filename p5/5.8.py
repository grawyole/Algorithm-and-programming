def solve_5_8(a, b, c):
  # Якщо a = 0, рівняння не квадратне
  if a == 0:
    # Тотожність 0 = 0 або рівняння без розв'язків
    if b == 0:
      return "немає розв'язку" if c != 0 else "безліч розв'язків"
    return f"лінійне: x={-c / b:.2f}"
  d = b * b - 4 * a * c
  if d > 0:
    x1 = (-b + d ** 0.5) / (2 * a)
    x2 = (-b - d ** 0.5) / (2 * a)
    return f"x1={x1:.2f}, x2={x2:.2f}"
  elif d == 0:
    return f"x={-b / (2 * a):.2f}"
  else:
    return "коренів немає"

# Тести:
print(solve_5_8(2, -8, 6))  # Очікується: x1=3.00, x2=1.00
print(solve_5_8(1, 4, 4))  # Очікується: x=-2.00
print(solve_5_8(1, 1, 1))  # Очікується: коренів немає
print(solve_5_8(0, 3, -6))  # Очікується: лінійне: x=2.00