def solve_5_5(a, b, c):
  # Трикутник не існує, якщо сума двох сторін не більша за третю
  if a + b <= c or a + c <= b or b + c <= a:
    return "не трикутник"
  elif a == b == c:
    return "рівносторонній"
  elif a == b or b == c or a == c:
    return "рівнобедрений"
  else:
    return "різносторонній"


# Тести:
print(solve_5_5(6, 8, 10))  # Очікується: різносторонній
print(solve_5_5(7, 7, 7))  # Очікується: рівносторонній
print(solve_5_5(1, 1, 5))  # Очікується: не трикутник
print(solve_5_5(4, 4, 6))  # Очікується: рівнобедрений