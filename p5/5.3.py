def solve_5_3(y):
  # Кратний 4 і не кратний 100, або кратний 400
  if (y % 4 == 0 and y % 100 != 0) or (y % 400 == 0):
    return "так"
  else:
    return "ні"

# Тести:
print(solve_5_3(2028))  # Очікується: так
print(solve_5_3(1700))  # Очікується: ні (кратний 100, але не 400)
print(solve_5_3(2000))  # Очікується: так (кратний 400)
print(solve_5_3(2021))  # Очікується: ні